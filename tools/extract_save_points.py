"""Typewriter and item box positions (aev types 6 and 8) for the rooms of data/save_points.json -> src/save_points.h.

Usage: python tools/extract_save_points.py "<game folder>"   (read only). A room whose own arc is missing is a variant of
another (31f is the Cabin 314 seen from the other side); VARIANT_OF names it."""
from pathlib import Path
import json
import sys
from extract_aev import records

ROOT = Path(__file__).resolve().parents[1]
VARIANT_OF = {'31f': '314'}
KINDS = {6: 0, 8: 1}  # aev type -> 0 typewriter, 1 item box


def main(game):
    rooms = {r['native_index']: r['room_id'] for r in json.loads((ROOT / 'data/rooms.json').read_text(encoding='utf-8'))}
    rows = []
    for sp in json.loads((ROOT / 'data/save_points.json').read_text(encoding='utf-8')):
        rid = rooms[sp['room']]
        found = {KINDS[t]: (x, z) for t, _no, x, z in records(VARIANT_OF.get(rid, rid), game) if t in KINDS}
        assert (0 in found) == sp['typewriter'] and (1 in found) == sp['item_box'], (rid, sp, found)
        rows += [(sp['room'], k, *found[k]) for k in sorted(found)]
    out = ['/* Generated by tools/extract_save_points.py from the rooms\' aev (types 6 and 8): do not edit. */',
           'static const struct { unsigned char room, kind; float wx, wz; } save_points[]={']
    out += ['{%d,%d,%.1ff,%.1ff},' % r for r in rows]
    out += ['};', '#define SAVE_POINT_COUNT %d' % len(rows), '']
    (ROOT / 'src/save_points.h').write_text('\n'.join(out), encoding='utf-8')
    print(len(rows), 'save points')


if __name__ == '__main__':
    main(sys.argv[1])
