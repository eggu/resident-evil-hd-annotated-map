"""Write src/item_name_text.h: the names of the ordinary (kind 7) items and the synthetic marks, drawn white (the run time tints
them: common items #B8BCC4, puzzles, files; user decision 2026-11-07: with [H] on every marker shows its name).

Names come from data/item_names.json (id -> English, Korean); the id of a kind 7 row is its 'item N' comment in src/labels.h.
Same font size, outline and wrapping as the other marker names (apply_name_rules.wrap). Raster bytes are B,G,R,A like labels.h.
Needs Pillow; run after render_labels.py and apply_name_rules.py."""
from pathlib import Path
import json
import re
from PIL import Image
from render_labels import ROOT, SIZES, block_size, draw_block
from apply_name_rules import drop_particle, wrap

COMMON_RGB = (255, 255, 255)  # all name rasters are white: the run time multiplies them by the category colour (INI [Colors])
PUZZLE_RGB = (255, 255, 255)
KEY_RGB = (254, 254, 254)  # distinct from DOC_RGB only so the size class below can tell key from file names
DOC_RGB = (255, 255, 255)  # document names
LANGS = ((1, 'ko', 1), (2, 'en', 0))  # label lang code, SIZES key, index in item_names.json
# Puzzle marks that have no label row (src/synth_marks.h): id >= 1000, name lines per language.
SYNTH = [(1001, ('주황색 램프',), ('Orange Lamp',)), (1002, ('녹색 램프',), ('Green Lamp',)), (1003, ('붉은 램프',), ('Red Lamp',)),
         (1010, ('비밀번호 문',), ('Passcode Door',)), (1011, ('MO 디스크 판독기',), ('MO Disk Reader',)),
         (1012, ('MO 디스크 판독기',), ('MO Disk Reader',)), (1013, ('MO 디스크 판독기',), ('MO Disk Reader',)),
         (1014, ('배리 깨우기',), ('Wake Barry',))]
DOCS = [(1020, ('유기화학 / 실험 문서',), ('Organic Chemistry / Lab Experiment',), DOC_RGB), (1021, ('케네스의 필름',), ("Kenneth's Film",), DOC_RGB),
        (1022, ('버려진 메모',), ('Crumpled Memo',), DOC_RGB), (1023, ('자살자의 / 유서',), ('Suicide Note',), DOC_RGB)]  # the game's file list (ko); en: evilresource


def main():
    h = (ROOT / 'src/labels.h').read_text(encoding='utf-8')
    names = json.loads((ROOT / 'data/item_names.json').read_text(encoding='utf-8'))
    table = h[h.index('static const Label labels[]={'):].split('\n')
    of_label = []
    for i, line in enumerate(l for l in table if l.startswith('{')):
        m = re.match(r'^\{7,.*\}, /\* item (\d+) \*/$', line)
        if m:
            of_label.append((i, int(m[1])))
    ids = sorted({item for _, item in of_label})
    images, rows = [], []
    for item in ids:
        for lang, key, at in LANGS:
            text = names[str(item)][at]
            lines = wrap(drop_particle(text) if key == 'ko' else text)
            size = SIZES[4, key]
            w, hh = block_size(lines, size)
            canvas = Image.new('RGBA', (w + 2, hh + 2))
            draw_block(canvas, lines, (w + 2) / 2, (hh + 2) / 2, size, COMMON_RGB[::-1])
            name = 'ntpx%d' % len(images)
            images.append('static const unsigned char %s[]={%s};' % (name, ','.join(map(str, canvas.tobytes()))))
            rows.append('{%d,%d,%s,%d,%d}, /* %s */' % (canvas.width, canvas.height, name, item, lang, text))
    for item, ko, en in SYNTH:
        for lang, key, _ in LANGS:
            lines = list((ko, en)[lang - 1])
            size = SIZES[2, key]
            w, hh = block_size(lines, size)
            canvas = Image.new('RGBA', (w + 2, hh + 2))
            draw_block(canvas, lines, (w + 2) / 2, (hh + 2) / 2, size, PUZZLE_RGB[::-1])
            name = 'ntpx%d' % len(images)
            images.append('static const unsigned char %s[]={%s};' % (name, ','.join(map(str, canvas.tobytes()))))
            rows.append('{%d,%d,%s,%d,%d}, /* %s */' % (canvas.width, canvas.height, name, item, lang, ' / '.join(lines)))
    for item, ko, en, colour in DOCS:
        for lang, key, _ in LANGS:
            lines = [t for t in ' / '.join((ko, en)[lang - 1]).split(' / ')]
            size = SIZES[4 if colour == KEY_RGB else 5, key]
            w, hh = block_size(lines, size)
            canvas = Image.new('RGBA', (w + 2, hh + 2))
            draw_block(canvas, lines, (w + 2) / 2, (hh + 2) / 2, size, colour[::-1])
            name = 'ntpx%d' % len(images)
            images.append('static const unsigned char %s[]={%s};' % (name, ','.join(map(str, canvas.tobytes()))))
            rows.append('{%d,%d,%s,%d,%d}, /* %s */' % (canvas.width, canvas.height, name, item, lang, ' '.join(lines)))
    out = ['/* Generated by tools/render_item_names.py: do not edit. */', *images,
           'static const struct { U32 w, h; const BYTE *px; U32 item, lang; } item_name_text[]={', *rows, '};',
           '#define NT_COUNT %d' % len(rows),
           '/* label index of each ordinary item row -> its item id (data/item_names.json) */',
           'static const struct { unsigned short label, item; } item_of_label[]={%s};' % ','.join('{%d,%d}' % p for p in of_label),
           '#define ITEM_OF_LABEL_COUNT %d' % len(of_label), '']
    (ROOT / 'src/item_name_text.h').write_text('\n'.join(out), encoding='utf-8')
    print('%d names, %d rows' % (len(rows), len(of_label)))


if __name__ == '__main__':
    main()
