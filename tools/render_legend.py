"""Write src/legend_text.h: the legend and readout rows added for the RE0 HD controls (user decision 2026-11-07).

Per language, in this order (LT_* in the header): icon opacity 10..100 with Shift, then with Ctrl; icon size 50..200 with
Shift, then with Ctrl; '[H] item names' All, No common and Off; '[~] hide' (beside the title); '[~] legend' (the folded panel);
'[\\] language' (the current language, user decision 2026-11-08: same row, colour and size as the [H] label).
Every raster is white with a dark outline; the run time multiplies it by its colour (the readouts grey, [H] and [\\] white, Off
and disabled rows #6A6A6A, INI [Colors] for the categories). Needs Pillow; run after render_labels.py."""
from pathlib import Path
import re
from PIL import Image
from render_labels import ROOT, SIZES, WHITE, legend_row

MODIFIERS = ('Shift', 'Ctrl')
OPACITY = range(10, 101, 10)
SIZE = range(50, 201, 10)
TEXT = {'ko': ('아이콘 불투명도', '아이콘 크기', ('[H] 아이템 이름: 모두', '[H] 아이템 이름: 일반 제외', '[H] 아이템 이름: 끔'), '[~] 숨김', '[~] 범례'),
        'en': ('Icon opacity', 'Icon size', ('[H] Item names: All', '[H] Item names: No common', '[H] Item names: Off'), '[~] Hide', '[~] Legend'),
        # zh_cn, the third language slot (data/zh_cn.json)
        'zh': ('图标不透明度', '图标大小', ('[H] 物品名称: 全部', '[H] 物品名称: 不含普通', '[H] 物品名称: 关'), '[~] 隐藏', '[~] 图例')}
LANGUAGE = {'ko': '[\\] 언어: 한국어', 'en': '[\\] LANGUAGE: ENGLISH', 'zh': '[\\] 语言: 简体中文'}
LANGS = ('ko', 'en', 'zh')  # block order in legend_text[]: LT_PER_LANG rows each


def rows(lang):
    opacity, size, names, hide, fold = TEXT[lang]
    out = []
    for mod in MODIFIERS:
        out += [('%s + [ · ] %s %d%%' % (mod, opacity, v), WHITE) for v in OPACITY]
    for mod in MODIFIERS:
        out += [('%s + - · + %s %d%%' % (mod, size, v), WHITE) for v in SIZE]
    return out + [(names[0], WHITE), (names[1], WHITE), (names[2], WHITE), (hide, WHITE), (fold, WHITE), (LANGUAGE[lang], WHITE)]


def main():
    images, table = [], []
    for lang in LANGS:
        for text, colour in rows(lang):
            canvas = legend_row(text, SIZES['legend', lang], colour, lang)
            name = 'ltpx%d' % len(images)
            images.append('static const unsigned char %s[]={%s};' % (name, ','.join(map(str, canvas.tobytes()))))
            table.append('{%d,%d,%s}, /* %s */' % (canvas.width, canvas.height, name, text))
    per = len(table) // len(LANGS)
    out = ['/* Generated by tools/render_legend.py: do not edit. */',
           *images,
           'static const struct { U32 w, h; const BYTE *px; } legend_text[]={',
           *table, '};',
           '#define LT_COUNT %d' % len(table),
           '#define LT_PER_LANG %d' % per,
           '#define LT_ICON_OPACITY 0  /* + modifier * %d + (value - 10) / 10 */' % len(OPACITY),
           '#define LT_ICON_SIZE %d /* + modifier * %d + (value - 50) / 10 */' % (2 * len(OPACITY), len(SIZE)),
           '#define LT_ITEM_NAMES %d /* All, No common, Off (item name state) */' % (2 * len(OPACITY) + 2 * len(SIZE)),
           '#define LT_HIDE %d' % (2 * len(OPACITY) + 2 * len(SIZE) + 3),
           '#define LT_FOLD %d' % (2 * len(OPACITY) + 2 * len(SIZE) + 4),
           '#define LT_LANG %d /* [\\] language: the current language */' % (2 * len(OPACITY) + 2 * len(SIZE) + 5), '']
    (ROOT / 'src/legend_text.h').write_text('\n'.join(out), encoding='utf-8')


if __name__ == '__main__':
    main()
