"""Write src/name_lines.h: where each line of a two-line (or longer) marker name sits in its raster, so the run time can draw
the lines aligned toward the icon (RE0 rule, user decision 2026-11-08) instead of centred. Each name stays one raster: a line is
a horizontal band of it, found as ink rows separated by at least 3 empty rows (the drawn gap is 4), and its ink columns.

Covers the marker names of labels.h (kinds 1, 2, 4, 5) and every name of item_name_text.h. Row counts are checked against the
' / ' line breaks of the row comments. Needs Pillow only; run after render_labels.py and render_item_names.py."""
from pathlib import Path
import re
from PIL import Image
from render_labels import ROOT, ROW, parse

MIN_GAP = 3


def bands(im):
    """[(y0, y1, x0, x1)] inclusive ink bounds of each line band, top to bottom."""
    w, h = im.size
    alpha = im.getchannel('A').load()
    rows = [any(alpha[x, y] for x in range(w)) for y in range(h)]
    out, y = [], 0
    while y < h:
        if not rows[y]:
            y += 1
            continue
        y0, gap = y, 0
        while y < h and (rows[y] or gap < MIN_GAP):
            gap = 0 if rows[y] else gap + 1
            y += 1
        y1 = y - gap - 1 if y < h or gap else h - 1
        cols = [x for x in range(w) for yy in range(y0, y1 + 1) if alpha[x, yy]]
        out.append((y0, y1, min(cols), max(cols)))
    return out


def entry(index, im, expect=None):
    found = bands(im)
    if expect is not None and len(found) != expect:
        raise SystemExit('name %d: %d bands found, %d lines expected' % (index, len(found), expect))
    return (index, found) if len(found) > 1 else None


def fmt(rows):
    return ','.join('{%d,%d,{%s}}' % (i, len(b), ','.join('{%d,%d,%d,%d}' % l for l in b + [(0, 0, 0, 0)] * (3 - len(b)))) for i, b in rows)


def main():
    h = (ROOT / 'src/labels.h').read_text(encoding='utf-8')
    arrays = dict(re.findall(r'static const unsigned char (px\d+)\[\]=\{([^}]*)\};', h))
    start, end, table = parse(h)
    label_rows = []
    for i, line in enumerate(l for l in table if l.startswith('{')):
        m = ROW.match(line)
        if not m or int(m['kind']) not in (1, 2, 4, 5):
            continue
        im = Image.frombytes('RGBA', (int(m['w']), int(m['h'])), bytes(map(int, arrays[m['px']].split(','))))
        if not im.getbbox():  # blank placeholder rows
            continue
        lines = re.sub(r'^[★◆◇□]', '', m['text']).split(' / ')
        e = entry(i, im, len(lines))
        if e:
            label_rows.append(e)
    n = (ROOT / 'src/item_name_text.h').read_text(encoding='utf-8')
    narr = dict(re.findall(r'static const unsigned char (ntpx\d+)\[\]=\{([^}]*)\};', n))
    name_rows = []
    for k, m in enumerate(re.finditer(r'^\{(\d+),(\d+),(ntpx\d+),\d+,\d+\}, /\* (.*) \*/$', n, re.M)):
        im = Image.frombytes('RGBA', (int(m[1]), int(m[2])), bytes(map(int, narr[m[3]].split(','))))
        e = entry(k, im)
        if e:
            name_rows.append(e)
    out = ['/* Generated by tools/gen_name_lines.py: do not edit. Line bands (inclusive ink rows and columns) of every name raster',
           ' * with two or more lines; marks.h-free data for the aligned name drawing in re1_mapnames.c. */',
           'typedef struct { unsigned short image; unsigned char lines; struct { short y0, y1, x0, x1; } line[3]; } NameLines;',
           'static const NameLines label_lines[]={%s};' % fmt(label_rows), '#define LABEL_LINES_COUNT %d' % len(label_rows),
           'static const NameLines nametext_lines[]={%s};' % fmt(name_rows), '#define NAMETEXT_LINES_COUNT %d' % len(name_rows), '']
    (ROOT / 'src/name_lines.h').write_text('\n'.join(out), encoding='utf-8')
    print(len(label_rows), 'label names,', len(name_rows), 'item names with several lines')


if __name__ == '__main__':
    main()
