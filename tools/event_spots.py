"""Write src/event_spots.h: the canvas point of the one event marker of each room whose events only know their room
(src/event_marks.h). Rule (user decision 2026-11-09): beside the room's drawn name, inside the room's own shape.

Candidates around the Korean name box (right, left, above, below, then the corners), first one whose icon square lies inside
the room shape; else the shape point nearest the name. A raster pixel is half a canvas unit (names are drawn for 1440 lines)."""
from pathlib import Path
import re
import room_geometry as rg

ROOT = Path(__file__).resolve().parents[1]
ICON = 9.0  # half the icon side in canvas units, plus a little air
GAP = 4.0
LABEL = re.compile(r'^\{0,(\d+),-1,\d+,\d+,0,0,1,([-\d.]+)f,([-\d.]+)f,[-\d.]+f,[-\d.]+f,(\d+),(\d+),px\d+,\d+,\d+,([-\d.]+)f,([-\d.]+)f,', re.M)
EVENT = re.compile(r'^    \{(\d+), \d+, \d+, \d+, [-\d.]+f, [-\d.]+f, 255, 6,', re.M)


def name_boxes():
    boxes = {}
    for m in LABEL.finditer((ROOT / 'src/labels.h').read_text(encoding='utf-8')):
        room, x, y, w, h, ax, ay = int(m[1]), float(m[2]), float(m[3]), int(m[4]), int(m[5]), float(m[6]), float(m[7])
        boxes.setdefault(room, (x - ax * .5, y - ay * .5, x - ax * .5 + w * .5, y - ay * .5 + h * .5))
    return boxes


def fits(shape, x, y, half=ICON):
    return all(shape.contains(x + dx, y + dy) for dx in (-half, 0, half) for dy in (-half, 0, half))


def spot(shape, box):
    l, t, r, b = box
    cx, cy = (l + r) / 2, (t + b) / 2
    for half in (ICON, ICON * .6):
        d = half + GAP
        for x, y in ((r + d, cy), (l - d, cy), (cx, t - d), (cx, b + d), (r + d, t - d), (l - d, t - d), (r + d, b + d), (l - d, b + d)):
            if fits(shape, x, y, half):
                return x, y
    # nearest room point clear of the name box (small rooms: the name fills most of them)
    x0, y0, x1, y1 = shape.bounds()
    pts = [(x0 + i, y0 + j) for i in range(0, int(x1 - x0) + 1) for j in range(0, int(y1 - y0) + 1)]
    inside = [p for p in pts if shape.contains(*p)]
    for m in (ICON, ICON * .6, 2.0):
        clear = [p for p in inside if not (l - m <= p[0] <= r + m and t - m <= p[1] <= b + m)]
        if clear:
            return min(clear, key=lambda p: (p[0] - cx) ** 2 + (p[1] - cy) ** 2)
    return min(inside, key=lambda p: (p[0] - cx) ** 2 + (p[1] - cy) ** 2)


def spots():
    shapes, boxes = rg.shapes(), name_boxes()
    rooms = sorted({int(r) for r in EVENT.findall((ROOT / 'src/event_marks.h').read_text(encoding='utf-8'))})
    return {room: spot(shapes[room], boxes[room]) for room in rooms}


def main():
    out = ['/* Generated by tools/event_spots.py: canvas point of each room-only event marker (beside the name, inside the room). */',
           'static const struct { unsigned char room; float x, y; } event_spots[] = {']
    out += ['    {%d, %.1ff, %.1ff},' % (room, x, y) for room, (x, y) in spots().items()]
    out += ['};', '']
    (ROOT / 'src/event_spots.h').write_text('\n'.join(out), encoding='utf-8')


if __name__ == '__main__':
    main()
