static int syn_bit(const unsigned *bank, unsigned n, unsigned size) { return n < size && (bank[n >> 5] >> (n & 31)) & 1; }
/* A lamp stays (the ! badge, then its eye once lit); the door shows until the Medical Room has been entered (b5 = visited rooms);
 * a file shows until its bit of the collected-files bitset is set. */
static int syn_visible(int s, const unsigned *b5, unsigned files) {
    if (synth_marks[s].file < 32) return !(files >> synth_marks[s].file & 1);
    if (s == SYN_BARRY) return syn_bit(b5, 148, 256); /* the Tyrant fight there comes first */
    if (s == SYN_DOOR_CELL) return !syn_bit(b5, 147, 256);
    return s != SYN_DOOR_MEDICAL || !syn_bit(b5, SYN_DOOR_ROOM, 256);
}
/* An event row: hidden once its flag bit is set in bank 0 (hide_bank 4, 256 bits), 1 (512), 2 (1024) or 3 (512); other rows are never hidden here. */
static int syn_event_visible(const Synth *r, const unsigned *b0, const unsigned *b1, const unsigned *b2, const unsigned *b3) {
    /* Native selectors bypass unused alternatives: Dining 0x4a3aa1..0x4a3b6d; Medical 0x4a0f88..0x4a0fdc and below. */
    if (r->kind == SYN_EVENT_KIND && r->hide_bank == 4) {
        if (r->room == 5 && r->hide_flag == 71 && syn_bit(b0, 66, 256)) return 0;
        if (r->room == 5 && r->hide_flag == 70 && syn_bit(b0, 68, 256)) return 0;
        if (r->room == 0 && r->chr == 0x20 && r->hide_flag == 69 && !syn_bit(b0, 34, 256)) return 0;
        /* Chris Main Hall 0x4a4023: scene 2 (sets b0[4]) plays only while bank1[3] is clear. */
        if (r->room == 6 && r->chr == 0x10 && r->hide_flag == 4 && syn_bit(b1, 3, 512)) return 0;
        /* Chris Medical ladder 0x4a07b7..0x4a08f3: steps 67/69 are skipped once b0[77] is set. */
        if (r->room == 0 && r->chr == 0x10 && (r->hide_flag == 67 || r->hide_flag == 69) && syn_bit(b0, 77, 256)) return 0;
    }
    if (r->kind == 2 && r->room == 148 && syn_bit(b0, 37, 256)) return 0; /* Barry dead: nobody to wake */
    if (r->kind == SYN_EVENT_KIND && r->room == 140 && r->hide_bank == 1 && r->hide_flag == 224) return 0; /* moved to the corridor */
    if (r->kind == SYN_EVENT_KIND && r->room == 137 && r->hide_flag == 272 && !syn_bit(b1, 332, 512)) return 0; /* not rescued yet */
    if (r->kind == SYN_EVENT_KIND && r->room == 133 && !syn_bit(b3, 483, 512)) return 0; /* film not taken: nothing to view */
    if (r->kind == SYN_EVENT_KIND && r->room == 5 && r->hide_bank == 4) {
        /* Dining Room (Jill): one scene at a time, in the native selector's order (0x4a3aa1); a skipped alternative counts as done. */
        static const unsigned order[] = {65, 71, 66, 67, 70, 68};
        for (unsigned k = 0; k < 6 && order[k] != r->hide_flag; k++) {
            unsigned f = order[k];
            int done = syn_bit(b0, f, 256) || (f == 71 && syn_bit(b0, 66, 256)) || (f == 70 && syn_bit(b0, 68, 256));
            if (!done) return 0;
        }
    }
    if (!r->hide_bank) return 1;
    if (r->hide_bank == 4) return !syn_bit(b0, r->hide_flag, 256);
    return !(r->hide_bank == 1 ? syn_bit(b1, r->hide_flag, 512) : r->hide_bank == 2 ? syn_bit(b2, r->hide_flag, 1024) : syn_bit(b3, r->hide_flag, 512));
}
/* item_name_text id of a mark's name; -1 for an event. */
static int syn_name_id(int s) {
    if (synth_marks[s].kind == SYN_EVENT_KIND) return -1; /* events have no name (RE0 rule): no raster, no name box */
    return SYN_BASE_NAME + (s >= SYN_DOC_ORGCHEM ? 20 + (s - SYN_DOC_ORGCHEM) : s == SYN_DOOR_MEDICAL || s == SYN_DOOR_CELL ? 10 : s >= SYN_MO_MORGUE ? 11 + (s - SYN_MO_MORGUE) : 1 + s); }
/* A lamp shows the ! badge until it is lit, then the eye it revealed (icons 97-99; the glyph belongs to the lamp, not to the
 * playthrough: the keypad draws the same three glyphs in the order of its code). */
#define SYN_SYMBOL_ICON 97
static int syn_icon(int s, const unsigned *b1, int badge) {
    return s <= SYN_LAMP_RED && syn_bit(b1, synth_marks[s].flag, 512) ? SYN_SYMBOL_ICON + s : badge;
}
